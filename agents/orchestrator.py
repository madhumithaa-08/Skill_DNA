def run_skill_capture_pipeline(
    artisan_description: str,
    craft_name: str,
    artisan_name: str,
    artisan_qa: dict,
) -> dict:
    """Run the complete SKILL DNA capture pipeline.

    Args:
        artisan_description: Free-text description of the craft process.
        craft_name: Name of the craft (e.g. 'Madurai Sungudi').
        artisan_name: Name of the master artisan.
        artisan_qa: Dict mapping question strings to artisan answer strings.

    Returns:
        dict with keys:
            fingerprint (dict | None): The generated Skill Fingerprint.
            lesson (dict | None): The generated lesson module.
            questions_asked (list): Questions generated by the Interviewer Agent.
            pipeline_status (dict): Stage completion info and any errors.
            success (bool): True if all stages completed without error.
    """
    pipeline_status: dict = {"stages": [], "errors": []}

    try:
        # ------------------------------------------------------------------ #
        # Stage 1: Observer                                                    #
        # ------------------------------------------------------------------ #
        print("[SKILL DNA] Stage 1: Observer Agent analysing craft description...")
        observer = ObserverAgent()
        observation = observer.analyze(artisan_description)
        pipeline_status["stages"].append({"stage": "observer", "status": "complete"})

        # ------------------------------------------------------------------ #
        # Stage 2: Interviewer                                                 #
        # ------------------------------------------------------------------ #
        print("[SKILL DNA] Stage 2: Interviewer Agent generating questions...")
        gaps = observation.get("knowledge_gaps", [])
        interviewer = InterviewerAgent()
        questions = interviewer.generate_questions(gaps, craft_name)
        pipeline_status["stages"].append({"stage": "interviewer", "status": "complete"})

        # ------------------------------------------------------------------ #
        # Stage 3: Knowledge Architect                                         #
        # ------------------------------------------------------------------ #
        print("[SKILL DNA] Stage 3: Knowledge Architect building Skill Fingerprint...")
        architect = KnowledgeArchitectAgent()
        fingerprint_result = architect.build_fingerprint(
            observation, artisan_qa, craft_name, artisan_name
        )
        pipeline_status["stages"].append(
            {"stage": "knowledge_architect", "status": "complete"}
        )

        # Extract the inner fingerprint dict if the architect returned a wrapper
        fingerprint = fingerprint_result.get("fingerprint", fingerprint_result)

        # ------------------------------------------------------------------ #
        # Stage 4: Curriculum                                                  #
        # ------------------------------------------------------------------ #
        print("[SKILL DNA] Stage 4: Curriculum Agent creating lesson module...")
        curriculum = CurriculumAgent()
        lesson = curriculum.create_lesson(
            fingerprint if isinstance(fingerprint, dict) else {}
        )
        pipeline_status["stages"].append({"stage": "curriculum", "status": "complete"})

        return {
            "fingerprint": fingerprint,
            "lesson": lesson,
            "questions_asked": questions,
            "pipeline_status": pipeline_status,
            "success": True,
        }

    except Exception as exc:  # pylint: disable=broad-except
        pipeline_status["errors"].append(str(exc))
        return {
            "fingerprint": None,
            "lesson": None,
            "questions_asked": [],
            "pipeline_status": pipeline_status,
            "success": False,
            "error": str(exc),
        }
