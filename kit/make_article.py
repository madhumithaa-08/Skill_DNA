"""
SKILL DNA — Honest-numbers article generator (strands-ship pattern: ss article).

Reads the REAL run files produced by the bench and the video recorder and
writes a Builder Center article whose "Measured results" section cites numbers
drawn verbatim from those files — never invented.

Inputs (both required — errors clearly if either is missing):
    kit/results/results.json     produced by  `python kit/ss.py bench`
    kit/results/video_run.json    produced by  `python kit/ss.py video --target local`

Outputs:
    demo/ARTICLE_GENERATED.md   a Builder Center article with real measured numbers
    demo/FACTS.md               a compact, paste-ready list of every measured number
                                with its source file path

The hand-written demo/BUILDER_CENTER_ARTICLE.md is left untouched; this generator
writes NEW files alongside it so the human narrative is preserved.

Usage:
    python kit/make_article.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "kit" / "results"
DEMO = ROOT / "demo"

RESULTS_JSON = RESULTS / "results.json"
VIDEO_JSON = RESULTS / "video_run.json"


def _strands_version() -> str:
    try:
        from importlib.metadata import version
        return version("strands-agents")
    except Exception:
        return "unknown"


def _load(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        raise SystemExit(f"ERROR: could not parse {path}: {exc}")


def _pct(x) -> str:
    try:
        return f"{int(round(float(x) * 100))}%"
    except Exception:
        return "n/a"


def facts(bench: dict, video: dict) -> str:
    """A compact bullet list of every measured number, each tagged with its source."""
    lines = [
        "# Facts — measured numbers for the SKILL DNA article",
        "",
        f"Generated: {bench.get('when', 'n/a')}",
        "",
        "Every number below was read from a run file produced by actually running the",
        "pipeline. Quote these exactly; do not round differently or add numbers not here.",
        "",
        "## Benchmark (kit/results/results.json — `python kit/ss.py bench`)",
        "",
        f"- Model: `{bench.get('model', 'n/a')}` in `{bench.get('region', 'n/a')}`",
        f"- Cases run: {bench.get('cases_run', 'n/a')}",
        f"- Overall pass rate: **{_pct(bench.get('overall_pass_rate', 0))}**",
    ]
    for label, s in bench.get("summary", {}).items():
        lines.append(f"- {label}: {s.get('cases', 'n/a')} cases · avg score **{s.get('score_avg', 'n/a')}**")
    bl = bench.get("baseline", {})
    lines += [
        f"- One-prompt baseline gap avg: {bl.get('gaps_avg', 'n/a')}",
        f"- One-prompt baseline tacit-question avg: {_pct(bl.get('tacit_q_avg', 0))}",
        "",
        "## Video run (kit/results/video_run.json — `python kit/ss.py video --target local`)",
        "",
        f"- Recorded length: **{video.get('seconds', 'n/a')}** s",
        f"- Under 3 minutes: **{video.get('under_3_min', 'n/a')}**",
        f"- Video file: {video.get('file', 'n/a')}",
    ]
    scenes = video.get("scenes", [])
    total_ev = sum(len(s.get("evidence", [])) for s in scenes)
    lines.append(f"- Scenes recorded: {len(scenes)} · evidence lines captured: {total_ev}")
    for s in scenes:
        lines.append(f"  - {s.get('title', 'scene')}: exit {s.get('exit', 'n/a')} · "
                     f"{len(s.get('evidence', []))} evidence lines")
    lines += [
        "",
        "## Per-case detail (kit/results/results.json)",
        "",
    ]
    for row in bench.get("rows", []):
        lines.append(f"- {row['id']} ({row['label']}): score {row['score']} · "
                     f"{'PASS' if row.get('passed') else 'FAIL'} · {row.get('detail', '')} · "
                     f"{row.get('latency_ms', 'n/a')} ms")
    lines += [
        "",
        f"## Tooling",
        "",
        f"- Strands Agents SDK version: `{_strands_version()}`",
        "",
        "> Generated by `python kit/make_article.py` (run via `python kit/ss.py article`)",
    ]
    return "\n".join(lines) + "\n"


def article(bench: dict, video: dict) -> str:
    """A Builder Center article whose results section cites real numbers only."""
    summary = bench.get("summary", {})
    obs = summary.get("observer", {})
    ka = summary.get("knowledge_architect", {})
    iv = summary.get("interviewer", {})
    cq = summary.get("curriculum_quiz", {})
    bl = bench.get("baseline", {})
    scenes = video.get("scenes", [])
    total_ev = sum(len(s.get("evidence", [])) for s in scenes)
    passed = sum(1 for r in bench.get("rows", []) if r.get("passed"))
    total = bench.get("cases_run", 0)

    md = [
        "# SKILL DNA: Preserving Craft Knowledge That Lives in Hands — Measured, Not Claimed",
        "",
        "*An AI platform that turns a master artisan's tacit, hands-on expertise into structured,",
        "interactive learning — built with Strands Agents on Amazon Bedrock. Pilot craft: Madurai Sungudi.*",
        "",
        "---",
        "",
        "## The problem",
        "",
        "India has **6.46 million artisans** (PIB 2026) across **318 GI-tagged crafts**. Much of what",
        "they know — the tension in a knot, the heat of a dye bath, the moment silk is ready — is tacit:",
        "it lives in their hands, not in any manual. When a master retires, that knowledge retires with them.",
        "SKILL DNA captures it before it disappears.",
        "",
        "## How it works",
        "",
        "Four Strands Agents run a structured capture pipeline on Amazon Bedrock Nova Pro:",
        "",
        "1. **Observer** — extracts visible steps and flags the tacit knowledge gaps a description leaves out.",
        "2. **Interviewer** — generates targeted questions for exactly those gaps (sensory, timing, judgement).",
        "3. **Knowledge Architect** — synthesises a permanent, artisan-approved Skill Fingerprint.",
        "4. **Curriculum** — turns the fingerprint into an interactive lesson with a quiz.",
        "",
        "Best-effort AWS services persist and voice the output: Amazon S3 (fingerprints), DynamoDB",
        "(learner progress), and Amazon Polly (audio). The Strands SDK version used is "
        f"`{_strands_version()}`.",
        "",
        "## Measured results",
        "",
        f"Numbers below are read verbatim from run files produced by actually running the pipeline",
        f"(benchmark: `kit/results/results.json`; video: `kit/results/video_run.json`). Run date: {bench.get('when', 'n/a')}.",
        "",
        f"**Benchmark — {total} signed cases scored against each case's expected answer**, model "
        f"`{bench.get('model', 'n/a')}` in `{bench.get('region', 'n/a')}`:",
        "",
        "| Label | Cases | Avg score |",
        "|--------|-------|-----------|",
    ]
    for label, s in summary.items():
        md.append(f"| {label} | {s.get('cases', 'n/a')} | **{s.get('score_avg', 'n/a')}** |")
    md += [
        f"| **overall** | **{total}** | **{_pct(bench.get('overall_pass_rate', 0))} pass rate** |",
        "",
        f"Comparison: the four agents passed **{passed}/{total}** cases. A one-prompt baseline (no",
        f"agents, no tools, no feedback loop) scored a gap-coverage average of **{bl.get('gaps_avg', 'n/a')}**",
        f"with a tacit-question average of **{_pct(bl.get('tacit_q_avg', 0))}** — the Observer→Interviewer",
        "feedback loop targets exactly the sensory knowledge the baseline skips.",
        "",
        "Per-case:",
        "",
    ]
    for row in bench.get("rows", []):
        md.append(f"- `{row['id']}` ({row['label']}): score **{row['score']}** · "
                  f"{'PASS' if row.get('passed') else 'FAIL'} · {row.get('detail', '')} · "
                  f"{row.get('latency_ms', 'n/a')} ms")

    md += [
        "",
        "**Demo video — recorded from a live run:**",
        "",
        f"- Length: **{video.get('seconds', 'n/a')} s** ({'under' if video.get('under_3_min') else 'OVER'} the 3-minute limit)",
        f"- Scenes: {len(scenes)} · evidence lines captured: {total_ev}",
    ]
    for s in scenes:
        md.append(f"  - {s.get('title', 'scene')}: exit code {s.get('exit', 'n/a')} · "
                  f"{len(s.get('evidence', []))} tagged evidence lines")
    md += [
        "",
        "## How to reproduce",
        "",
        "Run from the project root (AWS Bedrock credentials in `.env`):",
        "",
        "```bash",
        "python kit/ss.py bench                # score all signed cases -> kit/results/results.json",
        "python kit/ss.py video --target local # record the live demo -> kit/results/demo.mp4 + video_run.json",
        "python kit/ss.py article              # this article + demo/FACTS.md from real numbers",
        "python kit/ss.py check                # verify every submission artifact is present",
        "```",
        "",
        "Every number in the sections above came from those run files. A compact, paste-ready list",
        "of each measured number with its source file is in `demo/FACTS.md`.",
        "",
        "---",
        "",
        f"> Generated by `python kit/make_article.py` · Strands Agents SDK `{_strands_version()}`",
    ]
    return "\n".join(md) + "\n"


def main(argv=None) -> int:
    DEMO.mkdir(parents=True, exist_ok=True)

    if not RESULTS_JSON.exists():
        print("ERROR: kit/results/results.json not found.")
        print("       Run `python kit/ss.py bench` first to produce real benchmark numbers.")
        print("       This generator never invents numbers.")
        return 1
    if not VIDEO_JSON.exists():
        print("ERROR: kit/results/video_run.json not found.")
        print("       Run `python kit/ss.py video --target local` first to produce real video metrics.")
        print("       This generator never invents numbers.")
        return 1

    bench = _load(RESULTS_JSON)
    video = _load(VIDEO_JSON)
    if not bench or not video:
        print("ERROR: a required run file is empty or invalid. Re-run bench and video.")
        return 1

    article_path = DEMO / "ARTICLE_GENERATED.md"
    facts_path = DEMO / "FACTS.md"
    article_path.write_text(article(bench, video), encoding="utf-8")
    facts_path.write_text(facts(bench, video), encoding="utf-8")

    print(f"✅ Wrote {article_path}")
    print(f"✅ Wrote {facts_path}")
    print(f"   Numbers sourced from: {RESULTS_JSON} + {VIDEO_JSON}")
    print(f"   Strands SDK version: {_strands_version()}")
    print(f"   (demo/BUILDER_CENTER_ARTICLE.md left untouched)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
