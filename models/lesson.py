"""
Pydantic v2 models for SKILL DNA lesson modules.

A LessonModule is generated by the Curriculum Agent from a SkillFingerprint
and is the artifact consumed by learners in the Learner Studio.
"""
from pydantic import BaseModel, ConfigDict, field_validator


class QuizQuestion(BaseModel):
    """A multiple-choice quiz question with explanation."""

    model_config = ConfigDict(str_strip_whitespace=True)

    question: str
    options: list[str]  # exactly 4 items
    correct_answer: str
    explanation: str

    @field_validator("options")
    @classmethod
    def must_have_four_options(cls, v: list[str]) -> list[str]:
        if len(v) != 4:
            raise ValueError(f"options must have exactly 4 items, got {len(v)}")
        return v


class PracticeStep(BaseModel):
    """A single hands-on practice step in a lesson module."""

    model_config = ConfigDict(str_strip_whitespace=True)

    step_number: int
    instruction: str
    what_to_watch_for: str
    common_mistakes: str


class LessonModule(BaseModel):
    """
    A complete structured lesson module generated from a SkillFingerprint.

    Contains an overview, learning objectives, practice steps with sensory
    guidance, a quiz, and estimated duration.
    """

    model_config = ConfigDict(str_strip_whitespace=True)

    title: str
    level: str  # "beginner" | "intermediate" | "advanced"
    craft_name: str
    overview: str
    learning_objectives: list[str]
    practice_steps: list[PracticeStep]
    quiz: list[QuizQuestion]
    estimated_duration_minutes: int
